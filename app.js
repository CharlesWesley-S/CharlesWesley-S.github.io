function setLanguage(language) {
  const lang = language === "zh" ? "zh" : "en";
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = copy[lang][node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-language]").forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.language === lang)));
  document.title = document.body.dataset.page === "projects"
    ? (lang === "zh" ? "项目 · Charles Wesley" : "Projects · Charles Wesley")
    : (lang === "zh" ? "Charles Wesley · 网络安全 × AI Agent × 量子计算" : "Charles Wesley · Cybersecurity × AI Agents × Quantum");
  localStorage.setItem("cw-language", lang);
}

function initLanguage() {
  const saved = localStorage.getItem("cw-language");
  const browser = navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
  setLanguage(saved || browser);
  document.querySelectorAll("[data-language]").forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.language)));
}

function initNavigation() {
  const button = document.querySelector(".menu-button");
  const links = document.querySelector(".nav-links");
  if (!button || !links) return;
  button.addEventListener("click", () => {
    const open = links.classList.toggle("open");
    button.setAttribute("aria-expanded", String(open));
  });
  links.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
    links.classList.remove("open");
    button.setAttribute("aria-expanded", "false");
  }));
}

function initReveal() {
  const elements = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window)) { elements.forEach((element) => element.classList.add("visible")); return; }
  const observer = new IntersectionObserver((entries) => entries.forEach((entry) => {
    if (entry.isIntersecting) { entry.target.classList.add("visible"); observer.unobserve(entry.target); }
  }), { threshold: .12 });
  elements.forEach((element) => observer.observe(element));
}

async function loadGitHubStats() {
  const statNodes = document.querySelectorAll("[data-stat]");
  if (!statNodes.length) return;
  const fallback = { repos: "5", stars: "24", followers: "8", following: "17" };
  const render = (values) => statNodes.forEach((node) => { node.textContent = values[node.dataset.stat] ?? "—"; });
  render(fallback);
  try {
    const [userResponse, reposResponse] = await Promise.all([
      fetch("https://api.github.com/users/CharlesWesley-S"),
      fetch("https://api.github.com/users/CharlesWesley-S/repos?per_page=100&sort=updated")
    ]);
    if (!userResponse.ok || !reposResponse.ok) return;
    const user = await userResponse.json();
    const repos = await reposResponse.json();
    render({ repos: user.public_repos, followers: user.followers, following: user.following, stars: repos.reduce((total, repo) => total + repo.stargazers_count, 0) });
  } catch (_) { /* Static values remain visible if the public API is unavailable. */ }
}

function initCosmos() {
  const canvas = document.getElementById("cosmos");
  if (!canvas) return;
  const context = canvas.getContext("2d");
  const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)").matches;
  let width = 0, height = 0, stars = [], pointer = { x: -1000, y: -1000 };
  const resize = () => {
    const dpr = Math.min(devicePixelRatio || 1, 2);
    width = innerWidth; height = innerHeight;
    canvas.width = Math.floor(width * dpr); canvas.height = Math.floor(height * dpr);
    canvas.style.width = `${width}px`; canvas.style.height = `${height}px`; context.setTransform(dpr, 0, 0, dpr, 0, 0);
    const count = Math.min(170, Math.max(55, Math.floor(width * height / 9500)));
    stars = Array.from({ length: count }, () => ({ x: Math.random() * width, y: Math.random() * height, r: Math.random() * 1.35 + .25, vx: (Math.random() - .5) * .08, vy: Math.random() * .11 + .025, a: Math.random() * .68 + .18 }));
  };
  const draw = () => {
    context.clearRect(0, 0, width, height);
    for (const star of stars) {
      star.x += star.vx; star.y += star.vy;
      if (star.y > height + 4) star.y = -4; if (star.x < -4) star.x = width + 4; if (star.x > width + 4) star.x = -4;
      const distance = Math.hypot(star.x - pointer.x, star.y - pointer.y);
      const glow = distance < 130 ? (130 - distance) / 130 : 0;
      context.beginPath(); context.arc(star.x, star.y, star.r + glow * 1.4, 0, Math.PI * 2);
      context.fillStyle = `rgba(${glow ? "103,232,249" : "177,209,227"},${Math.min(1, star.a + glow * .5)})`; context.fill();
    }
    if (!reduceMotion) requestAnimationFrame(draw);
  };
  addEventListener("resize", resize); addEventListener("pointermove", (event) => { pointer = { x: event.clientX, y: event.clientY }; });
  resize(); draw();
}

