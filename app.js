function setLanguage(language) {
  const lang = language === "zh" ? "zh" : "en";
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = copy[lang][node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = copy[lang][node.dataset.i18nPlaceholder];
    if (value) node.setAttribute("placeholder", value);
  });
  document.querySelectorAll("[data-copy-en][data-copy-zh]").forEach((node) => {
    node.textContent = lang === "zh" ? node.dataset.copyZh : node.dataset.copyEn;
  });
  document.querySelectorAll("[data-placeholder-en][data-placeholder-zh]").forEach((node) => {
    node.setAttribute("placeholder", lang === "zh" ? node.dataset.placeholderZh : node.dataset.placeholderEn);
  });
  document.querySelectorAll("[data-language]").forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.language === lang)));
  const page = document.body.dataset.page;
  const titles = {
    projects: { en:"Projects · Charles Wesley", zh:"项目 · Charles Wesley" },
    notes: { en:"Knowledge Search · Charles Wesley", zh:"笔记搜索 · Charles Wesley" },
    "project-detail": { en:"Project Progress · Charles Wesley", zh:"项目进度 · Charles Wesley" },
    home: { en:"Charles Wesley · Cybersecurity × AI Agents × Quantum", zh:"Charles Wesley · 网络安全 × AI Agent × 量子计算" }
  };
  document.title = page === "post"
    ? (lang === "zh" ? document.body.dataset.titleZh : document.body.dataset.titleEn)
    : (titles[page] || titles.home)[lang];
  localStorage.setItem("cw-language", lang);
  noteState.lang = lang;
  renderNotes();
  renderProjectDetail(lang);
}

function renderNotes() {
  const grid = document.getElementById("notes-grid");
  if (!grid) return;
  const language = noteState.lang;
  const query = noteState.query.trim().toLowerCase();
  const matches = noteCatalog.filter((note) => {
    const categoryMatch = noteState.filter === "all" || note.category === noteState.filter;
    const haystack = [note.title.en,note.title.zh,note.description.en,note.description.zh,...note.tags].join(" ").toLowerCase();
    return categoryMatch && (!query || haystack.includes(query));
  });
  grid.textContent = "";
  matches.forEach((note) => {
    const card = document.createElement("a");
    card.className = "note-card"; card.href = note.url;
    card.innerHTML = `<div class="note-card-meta"><span>${note.date}</span><span>↗</span></div><h2>${note.title[language]}</h2><p>${note.description[language]}</p><div class="tag-row">${note.tags.map((tag)=>`<span>${tag}</span>`).join("")}</div>`;
    grid.appendChild(card);
  });
  const count = document.getElementById("note-count"); if (count) count.textContent = String(matches.length).padStart(2,"0");
  const empty = document.getElementById("notes-empty"); if (empty) empty.hidden = matches.length > 0;
}

function initNotes() {
  const input = document.getElementById("note-search");
  if (!input) return;
  input.addEventListener("input", () => { noteState.query = input.value; renderNotes(); });
  document.querySelectorAll("[data-note-filter]").forEach((button) => button.addEventListener("click", () => {
    noteState.filter = button.dataset.noteFilter;
    document.querySelectorAll("[data-note-filter]").forEach((item) => item.classList.toggle("active", item === button));
    renderNotes();
  }));
  addEventListener("keydown", (event) => {
    if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase() === "k") { event.preventDefault(); input.focus(); }
  });
}

function initPostSearch() {
  const input = document.getElementById("post-search");
  if (!input) return;
  const cards = [...document.querySelectorAll(".knowledge-card")];
  const count = document.getElementById("post-count");
  const empty = document.getElementById("post-empty");
  const filter = () => {
    const query = input.value.trim().toLowerCase();
    let visible = 0;
    cards.forEach((card) => {
      const match = !query || `${card.dataset.search || ""} ${card.textContent}`.toLowerCase().includes(query);
      card.hidden = !match;
      if (match) visible += 1;
    });
    if (count) count.textContent = String(visible).padStart(2,"0");
    if (empty) empty.hidden = visible > 0;
  };
  input.addEventListener("input", filter);
  filter();
}

